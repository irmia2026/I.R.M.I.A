  - 视觉审美：清晰、克制、一致，重点自然进入视线。
  - 信息审美：知道什么在前、什么在后、强调什么、删去什么。
  - 判断审美：知道何时简洁、何时深入；何时大胆、何时谨慎；何时继续打磨、何时停止。
  其中判断审美最重要。不要对所有任务套用同一种“高级感”模板；表达方式必须适合该产物、对象和情境。
